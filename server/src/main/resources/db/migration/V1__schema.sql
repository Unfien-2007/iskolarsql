-- =====================================================================
-- iskolarPath server schema (PostgreSQL)
-- Central scholarship catalog + user accounts for the desktop app.
-- =====================================================================

CREATE TABLE users (
    user_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL CHECK (role IN ('STUDENT', 'ADMIN')),
    is_active     BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP    NOT NULL DEFAULT now(),
    updated_at    TIMESTAMP    NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX users_email_lower_idx ON users (lower(email));

CREATE TABLE degree_programs (
    program_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_code   VARCHAR(20)  NOT NULL UNIQUE,
    program_name   VARCHAR(120) NOT NULL,
    field_category VARCHAR(60)
);

CREATE TABLE tags (
    tag_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tag_code    VARCHAR(40) NOT NULL UNIQUE,
    tag_name    VARCHAR(80) NOT NULL,
    description TEXT
);

CREATE TABLE document_types (
    document_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doc_code    VARCHAR(40) NOT NULL UNIQUE,
    doc_name    VARCHAR(80) NOT NULL,
    description TEXT
);

CREATE TABLE scholarships (
    scholarship_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_by           BIGINT       NOT NULL REFERENCES users (user_id),
    title                VARCHAR(200) NOT NULL,
    provider_name        VARCHAR(120) NOT NULL,
    provider_type        VARCHAR(40)  NOT NULL CHECK (provider_type IN
        ('GOVERNMENT', 'GOVERNMENT_OWNED_CORP', 'PRIVATE_CORPORATE',
         'NGO_FOUNDATION', 'UNIVERSITY', 'LOCAL_GOVERNMENT', 'INTERNATIONAL')),
    description          TEXT,
    tuition_benefit      VARCHAR(255),
    monthly_stipend      NUMERIC(12, 2),
    return_service_years INTEGER,
    application_url      VARCHAR(500),
    open_date            DATE,
    deadline_date        DATE,
    is_active            BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at           TIMESTAMP    NOT NULL DEFAULT now(),
    updated_at           TIMESTAMP    NOT NULL DEFAULT now()
);

CREATE TABLE scholarship_criteria (
    criteria_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scholarship_id      BIGINT       NOT NULL UNIQUE REFERENCES scholarships (scholarship_id) ON DELETE CASCADE,
    min_gwa_percentage  NUMERIC(5, 2),
    allow_failing_grade BOOLEAN      NOT NULL DEFAULT FALSE,
    max_annual_income   NUMERIC(12, 2),
    allowed_school_type VARCHAR(20)  CHECK (allowed_school_type IN ('PUBLIC', 'PRIVATE')),
    required_province   VARCHAR(80),
    required_city       VARCHAR(80)
);

CREATE TABLE scholarship_allowed_programs (
    scholarship_id BIGINT NOT NULL REFERENCES scholarships (scholarship_id) ON DELETE CASCADE,
    program_id     BIGINT NOT NULL REFERENCES degree_programs (program_id) ON DELETE CASCADE,
    PRIMARY KEY (scholarship_id, program_id)
);

CREATE TABLE scholarship_allowed_years (
    scholarship_id BIGINT  NOT NULL REFERENCES scholarships (scholarship_id) ON DELETE CASCADE,
    year_level     INTEGER NOT NULL,
    PRIMARY KEY (scholarship_id, year_level)
);

CREATE TABLE scholarship_required_tags (
    scholarship_id BIGINT  NOT NULL REFERENCES scholarships (scholarship_id) ON DELETE CASCADE,
    tag_id         BIGINT  NOT NULL REFERENCES tags (tag_id) ON DELETE CASCADE,
    is_mandatory   BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (scholarship_id, tag_id)
);

CREATE TABLE scholarship_documents (
    scholarship_id   BIGINT NOT NULL REFERENCES scholarships (scholarship_id) ON DELETE CASCADE,
    document_type_id BIGINT NOT NULL REFERENCES document_types (document_type_id) ON DELETE CASCADE,
    PRIMARY KEY (scholarship_id, document_type_id)
);

CREATE TABLE app_state (
    key        VARCHAR(80) PRIMARY KEY,
    value      TEXT        NOT NULL,
    updated_at TIMESTAMP   NOT NULL DEFAULT now()
);
